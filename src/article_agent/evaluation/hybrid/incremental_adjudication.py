"""Plan and gate incremental FIELD judging; existing evaluator/judge rules are unchanged."""
from collections import Counter
from copy import deepcopy

from ..entity_matcher import entities
from .engine import evaluate_article_hybrid
from .models import JudgmentArtifact
from .semantic_judge import (
    CachedSemanticJudge, canonical_json, digest, field_representation, field_request,
)

MODEL = "gpt-5.6-sol"


def validated_successes(artifacts):
    """Reuse the existing cache contract, rejecting conflicting duplicate entries."""
    reader = CachedSemanticJudge(model=MODEL)
    values = {}
    for raw in artifacts:
        item = JudgmentArtifact.model_validate(raw)
        reader._validate(item, item.canonical_input)
        if item.status != "SUCCESS":
            continue
        if item.input_sha256 in values and values[item.input_sha256] != raw:
            raise ValueError("Conflicting successful judgments for a frozen cache key")
        values[item.input_sha256] = deepcopy(raw)
    return values


def plan_targets(prediction, gold, registry, overlay, before, prior_identity_report, old_artifacts):
    """Explicitly target newly matched, PRESENT/PRESENT semantic FIELD cache misses.

    IDs belong in this manifest. The wire request/cache key is generated by the
    unchanged PR5E-1 field_request/canonical_input functions (no new instructions).
    """
    old = validated_successes(old_artifacts)
    judge = CachedSemanticJudge(artifacts=list(old.values()), model=MODEL)
    specs, semantics = {f.field_id: f for f in registry.fields}, overlay.by_id()
    pairs = {(m.entity_type, m.gold_entity_id): m.prediction_entity_id
             for m in before.entity_matches if m.match_status == "MATCHED"}
    prior = {f.target_id: f for f in prior_identity_report.field_results}
    previous_judgments = {j.judgment_id: j for j in before.semantic_judgments}
    targets, excluded, cache_hits = [], [], []
    scorable = 0
    for field in before.field_results:
        pid = pairs.get((field.entity_type, field.gold_entity_id))
        reason = None
        if pid is None or field.prediction_entity_id != pid:
            reason = "IDENTITY_UNRESOLVED"
        elif field.gold_status != "PRESENT" or field.prediction_status != "PRESENT":
            reason = ("SOURCE_CONFLICT_OR_STATUS" if "SOURCE_CONFLICT" in {
                field.gold_status, field.prediction_status} else "MISSINGNESS_OR_NOT_EXTRACTED")
        elif field.field_id not in semantics:
            reason = "DETERMINISTIC_FIELD_NOT_SEMANTIC"
        if reason:
            excluded.append({"target_id": field.target_id, "reason": reason})
            continue
        scorable += 1
        spec = specs[field.field_id]
        if not spec.enabled:
            raise ValueError("Baseline contains a disabled semantic field")
        g = getattr(entities(gold.truth, field.entity_type)[field.gold_entity_id], spec.field_path)
        p = getattr(entities(prediction, field.entity_type)[pid], spec.field_path)
        if (g.status.value, p.status.value, g.value, p.value) != (
                field.gold_status, field.prediction_status, field.gold_value, field.prediction_value):
            raise ValueError("Frozen field representation drift")
        if field.semantic_method == "DETERMINISTIC_EXACT":
            excluded.append({"target_id": field.target_id, "reason": "DETERMINISTIC_FAST_PATH"})
            continue
        request = field_request(semantics[field.field_id],
                                field_representation(gold.truth, g), field_representation(prediction, p))
        canonical = judge.canonical_input(request)
        key = digest(canonical)
        if key in old:
            cached = judge.judge(request)
            cache_hits.append({"target_id": field.target_id, "cache_key": key, "judgment_id": cached.judgment_id})
            continue
        if (field.hybrid_classification != "JUDGE_UNAVAILABLE"
                or field.target_id not in prior or prior[field.target_id].prediction_entity_id is not None):
            excluded.append({"target_id": field.target_id, "reason": "NOT_NEWLY_SCORABLE_CACHE_MISS"})
            continue
        artifact = previous_judgments.get(field.semantic_judgment_id)
        if artifact is None or artifact.status != "JUDGE_UNAVAILABLE":
            raise ValueError("Newly scorable field lacks its frozen unavailable artifact")
        judge._validate(artifact, canonical)
        if artifact.input_sha256 != key:
            raise ValueError("Field request differs from frozen PR5F-1 request")
        targets.append({
            "target_key": field.target_id, "cache_key": key,
            "entity_type": field.entity_type, "gold_entity_id": field.gold_entity_id,
            "prediction_entity_id": pid, "field_id": field.field_id,
            "gold": {"status": g.status.value, **deepcopy(canonical["gold"])},
            "prediction": {"status": p.status.value, **deepcopy(canonical["prediction"])},
            "in_hard_denominator": field.in_hard_denominator,
            "cache_lookup": "NO_SUCCESSFUL_FROZEN_JUDGMENT",
            "eligibility_reason": "NEWLY_MATCHED_PRESENT_SEMANTIC_FIELD_WITH_FROZEN_CACHE_MISS",
            "request": request, "canonical_input": canonical,
        })
    targets.sort(key=lambda t: t["target_key"])
    if len({t["target_key"] for t in targets}) != len(targets):
        raise ValueError("Duplicate adjudication target IDs")
    return {
        "total_field_targets": len(before.field_results),
        "total_scorable_semantic_targets": scorable,
        "old_successful_cache_count": len(old),
        "cached_successful_field_targets": len(cache_hits),
        "cached_successful_unique_keys_used": len({h["cache_key"] for h in cache_hits}),
        "old_cached_field_hits": cache_hits,
        "new_cache_miss_targets": len(targets),
        "new_unique_api_requests": len({t["cache_key"] for t in targets}),
        "technical_unresolved": sum(j.status == "JUDGE_UNAVAILABLE" and j.attempts > 0
                                    for j in before.semantic_judgments),
        "excluded_targets_by_reason": dict(sorted(Counter(e["reason"] for e in excluded).items())),
        "excluded_targets": excluded, "targets": targets,
    }


class ManifestOnlyJudge:
    """The live judge cannot receive any request outside the approved target manifest."""
    def __init__(self, live, plan, old_artifacts):
        if live.model != MODEL or live.client.model != MODEL or live.client.api_mode != "responses":
            raise ValueError("Frozen adjudication requires gpt-5.6-sol Responses")
        self.live = live
        self.old = CachedSemanticJudge(artifacts=list(validated_successes(old_artifacts).values()), model=MODEL)
        self.allowed = {t["cache_key"]: t["canonical_input"] for t in plan["targets"]}
        self.new = {}

    def judge(self, request):
        canonical = self.old.canonical_input(request)
        key = digest(canonical)
        if key in self.old.frozen:
            return self.old.judge(request)
        if key not in self.allowed or self.allowed[key] != canonical or request["judge_type"] != "FIELD":
            raise ValueError("API request outside the frozen newly-scorable manifest")
        result = self.live.judge(request)
        self.old._validate(result, canonical)
        self.new[key] = result.model_dump(mode="json")
        return result


def merge_judgments(old_artifacts, new_artifacts, plan):
    """Old payloads remain byte-equivalent under the existing canonical JSON encoding."""
    old = validated_successes(old_artifacts)
    allowed = {t["cache_key"]: t["canonical_input"] for t in plan["targets"]}
    validator = CachedSemanticJudge(model=MODEL)
    new = {}
    for raw in new_artifacts:
        item = JudgmentArtifact.model_validate(raw)
        key = item.input_sha256
        if key not in allowed or key in old:
            raise ValueError("New judgment is not an eligible cache miss")
        validator._validate(item, allowed[key])
        if key in new and new[key] != raw:
            raise ValueError("Duplicate new judgment with different payload")
        new[key] = deepcopy(raw)
    combined = [deepcopy(raw) for raw in old_artifacts]
    combined.extend(new[key] for key in sorted(new))
    combined_by_key = {r["input_sha256"]: r for r in combined}
    if any(canonical_json(raw) != canonical_json(combined_by_key[key]) for key, raw in old.items()):
        raise ValueError("Historical judgment payload changed")
    return combined


def replay_frozen_pairs(prediction, gold, registry, overlay, before, artifacts):
    """Only field adjudication changes; pair selection is the frozen PR5F-1 input."""
    judge = CachedSemanticJudge(artifacts=artifacts, model=MODEL)
    after = evaluate_article_hybrid(
        prediction, gold, registry, overlay, judge,
        prediction_sha256=before.prediction_sha256, gold_sha256=before.gold_sha256,
        precomputed_matches=before.entity_matches)
    if after.entity_matches != before.entity_matches:
        raise ValueError("STOP: frozen entity mappings changed")
    for key in ("hybrid_entity_metrics", "conflicts", "hybrid_status_accuracy"):
        if after.metrics[key] != before.metrics[key]:
            raise ValueError("STOP: frozen identity/status/conflict metrics changed: " + key)
    if after.metrics["hybrid_production_coverage"] != before.metrics["hybrid_production_coverage"]:
        raise ValueError("STOP: production coverage changed")
    if (after.metrics["hybrid_hard_acceptable"]["denominator"] != before.metrics["hybrid_hard_acceptable"]["denominator"]
        or after.metrics["hard_failure_decomposition"]["IDENTITY_UNRESOLVED"]
        != before.metrics["hard_failure_decomposition"]["IDENTITY_UNRESOLVED"]):
        raise ValueError("STOP: frozen denominator/identity-unresolved targets changed")
    return after
